Where the specific call/topic conditions require a Technology Readiness Level (TRL), the following definitions apply, unless otherwise specified:

– TRL 1 — Basic principles observed

– TRL 2 — Technology concept formulated

– TRL 3 — Experimental proof of concept

– TRL 4 — Technology validated in a lab

– TRL 5 — Technology validated in a relevant environment (industrially relevant environment in the case of key enabling technologies)

– TRL 6 — Technology demonstrated in a relevant environment (industrially relevant environment in the case of key enabling technologies)

– TRL 7 — System prototype demonstration in an operational environment

– TRL 8 — System complete and qualified

– TRL 9 — Actual system proven in an operational environment (competitive manufacturing in the case of key enabling technologies, or in space)

Source: Horizon Europe Work Programme 2023-2025, 13. General Annexes (Commission Decision C(2025) 2779 of 14 May 2025), Annex B — Eligibility, "Technology Readiness Levels".'
